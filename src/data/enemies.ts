/** id 归一化:去除分隔符、统一小写 — 兼容 yeLang/ye_lang、shanZei/shanzei 等 */
function norm(id: string): string {
  return id.replace(/[_\-\s]/g, '').toLowerCase();
}

const ENEMY_INDEX = new Map(ENEMIES.map((e) => [norm(e.id), e]));

export function getEnemy(id: string): Enemy | undefined {
  return ENEMY_INDEX.get(norm(id)) ?? ENEMIES.find((e) => e.name === id.trim());
}
