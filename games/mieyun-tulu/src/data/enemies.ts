export const ENEMY_BY_ID: Record<string, EnemyDef> = Object.fromEntries(
  ENEMIES.map((e) => [e.id, e]),
);

export function enemyById(id: string): EnemyDef | null {
  return ENEMY_BY_ID[id] ?? null;
}

/** Ordinary foes appropriate to a realm order — tribulations excluded. */
export function enemiesForRealm(order: number): EnemyDef[] {
  const pool = ENEMIES.filter((e) => !e.isCalamity && e.realmOrder === Math.max(1, order));
  if (pool.length > 0) return pool;
  return ENEMIES.filter((e) => !e.isCalamity && e.realmOrder === 1);
}
