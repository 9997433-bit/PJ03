/**
 * events.ts — 遭遇表 (48 events across five omen buckets)
 *
 * Every 探索 turn casts a D100, offsets it by 气运 and 劫运, and lands in one of
 * five buckets: 大凶 / 小凶 / 平 / 小吉 / 大吉. A second audited roll picks
 * within the bucket. `destiny` events sit off the wheel entirely — they are
 * drawn only when their flag chain is already satisfied, which is what makes
 * the 图录 hunt feel authored rather than random.
 *
 * Choices publish their own odds. The engine hands the UI a `ResolvedChoice`
 * with the D20 check already computed against the character's attribute, so a
 * player is always deciding under stated probability, never under mystery.
 * That is the whole design thesis of this game: the dice are public, the
 * accounting is public, and you still lose.
 */

