export const OPPONENT_BY_ID: Record<string, OpponentDef> = Object.fromEntries(
  OPPONENTS.map((o) => [o.id, o]),
);

export function getOpponent(id: string): OpponentDef | undefined {
  return OPPONENT_BY_ID[id];
}

/** Opponents who can be met at a given place. */
export function opponentsAt(placeId: string): OpponentDef[] {
  return OPPONENTS.filter((o) => o.title.split('·')[0] === PLACE_TITLES[placeId]);
}

